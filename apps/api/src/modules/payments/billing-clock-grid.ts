import { CronExpression } from '@nestjs/schedule';

/**
 * Розклад billing-clock і вирівнювання дат, які він читає: це одне рішення,
 * тож живе в одному місці.
 *
 * Клок тикає за розкладом нижче і бере лише вже настале (`$lte: now`). Дата,
 * збережена з секундами (`Date.now() + 24 год`, де `now` — тик плюс кілька
 * секунд обробки), у тик своєї ж години не влазить і чекає наступного: кожен
 * повтор прострочки зсувався б на годину вперед, а за десять спроб набігло б
 * пів доби. Тому дата наступної спроби списання лягає рівно на сітку.
 *
 * Разові дати «не раніше ніж» (холд повтору на час оплати зі сторінки банку)
 * вирівнювати не треба і не можна плутати з цим: тик однаково забирає все, що
 * вже настало, тож підняття на найближчий тик не зсунуло б нічого — лише
 * приховало б, що таке вікно завжди триває до наступного тику.
 *
 * Межа циклу (`currentPeriodEnd`, вона ж `nextChargeAt`) на сітці не лежить і
 * не мусить: вона тримає час доби першої оплати і рахується від якір-дня, тож
 * місячне списання просто відбувається на першому тику після неї — до години
 * пізніше, однаково кожного місяця, без накопичення.
 */
export const BILLING_CLOCK_CRON = CronExpression.EVERY_HOUR;

const MINUTE_MS = 60 * 1000;
const HOUR_MS = 60 * MINUTE_MS;

/** «Щогодини» у полі годин записують чотирма способами — усі рівнозначні. */
const EVERY_HOUR_FIELD = new Set(['*', '*/1', '0-23', '0-23/1']);

/**
 * Крок сітки — з самого розкладу, а не окремим числом поруч: інакше зміна
 * розкладу мовчки лишила б вирівнювання на старому кроці і повернула б рівно
 * той дрейф, заради якого воно й з'явилось.
 *
 * Приймаються лише рівномірні розклади з кроком не більшим за годину:
 * погодинний (`0 0-23/1 * * *`) або хвилинний з кроком N, що ділить 60.
 * Вирівнювання рахується від epoch, тож тик збігається з рівною хвилиною чи
 * рівною годиною часу сервера, поки його зсув від UTC цілогодинний (UTC,
 * Europe/Kyiv). Крок у кілька годин цю властивість втрачає, а «раз на день»
 * чи «по понеділках» — узагалі не сітка. Такий розклад падає тут, на імпорті,
 * а не мовчки зсуває дати списань.
 */
export function tickMsFromCron(expression: string): number {
    const fields = expression.trim().split(/\s+/);
    const fail = (reason: string): never => {
        throw new Error(
            `❌ BILLING_CLOCK_CRON ("${expression}") ${reason}. ` +
                'Вирівнювання дат клока потребує рівномірної сітки з кроком ≤ 1 год.'
        );
    };
    if (fields.length !== 5 && fields.length !== 6) {
        return fail('мусить мати 5 або 6 полів');
    }
    // П'ятипольний запис — без секунд (саме так записані погодинні
    // `CronExpression`, тоді як хвилинні мають шість полів).
    const [second, minute, hour, dayOfMonth, month, weekday] =
        fields.length === 5 ? ['0', ...fields] : fields;
    if (second !== '0') return fail('мусить стартувати на нульовій секунді');
    if (dayOfMonth !== '*' || month !== '*' || weekday !== '*') {
        return fail('мусить працювати щодня');
    }
    if (!EVERY_HOUR_FIELD.has(hour)) return fail('мусить працювати щогодини');
    if (minute === '0') return HOUR_MS;
    // Голий `*` — той самий крок в одну хвилину, що й `*/1` (так само, як `*`
    // у полі годин); класичний п'ятипольний «щохвилини» пишуть саме ним.
    const everyNMinutes = /^\*(?:\/([0-9]{1,2}))?$/.exec(minute);
    const step = everyNMinutes ? Number(everyNMinutes[1] ?? '1') : 0;
    if (step < 1 || 60 % step !== 0) {
        return fail('мусить тикати рівними частками години');
    }
    return step * MINUTE_MS;
}

const TICK_MS = tickMsFromCron(BILLING_CLOCK_CRON);

/**
 * Тик, не пізніший за `at` — для інтервальних дат (наступна спроба списання).
 * Округлення саме вниз: вгору дало б час на крок пізніше за тик, який мусив би
 * його взяти, і зсув лишився б на місці.
 */
export function alignToClockTick(at: Date): Date {
    return new Date(Math.floor(at.getTime() / TICK_MS) * TICK_MS);
}
